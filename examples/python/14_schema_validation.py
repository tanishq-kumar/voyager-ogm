"""Voyager OGM: Schema Validation & Diagnostic Suggestions.

Teaches:
    - Registering domain models into the native `SchemaRegistry`
    - Validating Cypher queries ahead-of-time before executing against databases
    - Catching label and relationship typos with Levenshtein fuzzy diagnostic suggestions
    - Enforcing strict query safety with `report.raise_if_invalid()`
    - Handling `SchemaValidationError` with actionable fix recommendations

Prerequisites:
    - Engine: None (runs offline / in-memory; no database needed)
    - Extras: None

Run with:
    `uv run python examples/python/14_schema_validation.py`
"""

from __future__ import annotations

from voyager_ogm import (
    Field,
    Node,
    Relationship,
    SchemaRegistry,
    SchemaValidationError,
    node,
    relationship,
    validate_query,
)


@node(labels=["Person"])
class Person(Node):
    name: str = Field(primary_key=True)
    age: int = Field(default=30)


@node(labels=["Movie"])
class Movie(Node):
    title: str = Field(primary_key=True)
    released: int = Field(default=2000)


@relationship(type_name="ACTED_IN")
class ActedIn(Relationship):
    role: str = Field(default="Actor")


def main() -> None:
    print("=" * 70)
    print("[Example 14] Schema Validation & Diagnostic Suggestions")
    print("=" * 70)

    # 1. Global registry holds auto-registered Node models (@node auto-registers)
    reg = SchemaRegistry.global_registry()
    # Explicitly register relationship topology contract (source -> relationship -> target)
    reg.register_relationship(
        name="ActedIn",
        type_name="ACTED_IN",
        source_labels=["Person"],
        target_labels=["Movie"],
        fields={"role": {"type": "STRING"}},
        directed=True,
    )
    print("1. Registered Schema Entities: Person, Movie, ACTED_IN\n")

    # -------------------------------------------------------------------------
    # 2. Inspect a query generated by an LLM or user with a typo ('Persn')
    # -------------------------------------------------------------------------
    # Advanced: raw query — validating arbitrary incoming query strings (e.g. LLM/Agent generated text)
    bad_query = "MATCH (p:Persn)-[r:ACTED_IN]->(m:Movie) RETURN p.name, m.title"
    print(f"2. Validating LLM/Agent Raw Query String:\n   {bad_query}\n")

    report = validate_query(bad_query)
    print(f"   Validation Passed : {report.is_valid}")
    print(f"   Diagnostic Count  : {len(report.diagnostics)}")

    # 3. Inspect diagnostics with intelligent error codes and suggestions
    for diag in report.diagnostics:
        print("\n   [Diagnostic Detected]")
        print(f"     Severity   : {diag.severity.upper()}")
        print(f"     Code       : {diag.code}")
        print(f"     Entity     : {diag.entity_id}")
        print(f"     Message    : {diag.message}")
        if diag.suggestion:
            print(f"     Suggestion : {diag.suggestion}")

    # 4. Demonstrate raising SchemaValidationError
    print("\n3. Enforcing query safety with report.raise_if_invalid():")
    try:
        report.raise_if_invalid()
    except SchemaValidationError as exc:
        print(f"   [CAUGHT EXPECTED ERROR]: {exc}\n")

    # -------------------------------------------------------------------------
    # 5. Validate a conforming query string (escape hatch) & fluent Query object
    # -------------------------------------------------------------------------
    # Advanced: raw query — validating user text input against registered schema
    good_query = "MATCH (p:Person)-[r:ACTED_IN]->(m:Movie) RETURN p.name, m.title"
    print(f"4. Validating Corrected Raw Query String:\n   {good_query}")
    valid_report = validate_query(good_query)
    valid_report.raise_if_invalid()
    print(f"   Validation Passed : {valid_report.is_valid} (0 errors)\n")

    # 6. Validate native OGM Query builder object
    from voyager_ogm import Query

    ogm_q = (
        Query.match("p", labels=["Person"])
        .to(["ACTED_IN"], "r")
        .node("m", labels=["Movie"])
        .return_("p.name", "m.title")
    )
    ogm_report = ogm_q.validate()
    print(f"5. Validating Fluent OGM Query Object: passed = {ogm_report.is_valid}")
    print("=" * 70)


if __name__ == "__main__":
    main()
