def _is_port_open(host: str, port: int, timeout: float = 0.3) -> bool:
    """Fast socket probe to detect whether a container port is actively listening."""
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


